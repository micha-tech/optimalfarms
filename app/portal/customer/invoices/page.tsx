"use client";

import Link from "next/link";
import { FileText, Download, Receipt } from "lucide-react";
import PortalShell from "@/components/portals/PortalShell";
import { Badge } from "@/components/portals/UI";
import { useApp } from "@/components/providers/AppProvider";
import { naira, shortDate } from "@/lib/utils";

export default function InvoicesPage() {
  const { orders, user, pushToast } = useApp();
  const mine = orders.filter((o) => !user || o.customerEmail === user.email || o.customerId === user.id);

  return (
    <PortalShell section="customer" title="My Invoices" subtitle="Download invoices and receipts for your orders.">
      <div className="grid gap-4 sm:grid-cols-3">
        {[["Invoices issued", mine.length], ["Total invoiced", naira(mine.reduce((s, o) => s + o.total, 0))], ["Receipts available", mine.filter((o) => o.paymentStatus === "Paid").length]].map(([k, v]) => (
          <div key={k} className="card p-4"><p className="text-[0.7rem] font-bold uppercase tracking-wider text-muted">{k}</p><p className="mt-2 font-display text-xl font-bold text-forest">{v}</p></div>
        ))}
      </div>
      <div className="card mt-5 overflow-hidden">
        <div className="border-b border-[#edf1ed] px-5 py-4"><h3 className="font-display text-[1.05rem] font-bold text-forest">Tax invoices</h3></div>
        <div className="table-wrap">
          <table className="data">
            <thead><tr><th>Invoice no.</th><th>Order reference</th><th>Date</th><th>Amount</th><th>Status</th><th>Download</th></tr></thead>
            <tbody>
              {mine.map((o) => (
                <tr key={o.id}>
                  <td className="font-bold text-forest">INV-{o.reference.slice(-8)}</td>
                  <td>{o.reference}</td>
                  <td>{shortDate(o.createdAt)}</td>
                  <td className="font-bold text-forest">{naira(o.total)}</td>
                  <td><Badge text={o.paymentStatus === "Credit Approved" ? "Credit invoice" : o.paymentStatus} tone={o.paymentStatus === "Paid" ? "green" : "blue"} /></td>
                  <td className="flex gap-2">
                    <button onClick={() => pushToast(`Invoice INV-${o.reference.slice(-8)} prepared for download.`, "info")} className="btn btn-outline btn-sm"><Download size={13} /> PDF</button>
                    <button onClick={() => pushToast("Excel export would be generated by the reporting service.", "info")} className="btn btn-ghost btn-sm text-[0.72rem]">Excel</button>
                  </td>
                </tr>
              ))}
              {mine.length === 0 && <tr><td colSpan={6} className="py-10 text-center text-muted">No invoices yet.</td></tr>}
            </tbody>
          </table>
        </div>
      </div>
      <div className="mt-5 card flex items-center gap-3 p-5">
        <Receipt size={20} className="text-leaf" />
        <div><p className="text-[0.82rem] font-bold text-forest">Need a receipt for a payment?</p><p className="text-[0.74rem] text-muted">Receipts are issued automatically once a payment is verified or credit is approved.</p></div>
        <Link href="/portal/customer/payments" className="btn btn-outline btn-sm ml-auto">View payments</Link>
      </div>
    </PortalShell>
  );
}
